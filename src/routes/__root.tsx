function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  // The standalone /quote page and every admin dashboard are intentionally
  // chrome-free: no chat bubble, no sticky bar, no nav, no footer.
  const bare = useRouterState({
    select: (s) => {
      const path = s.location.pathname.replace(/\/+$/, "");
      // Paused: the resting homepage has no chat bubble or booking bar.
      return path === "" || path === "/quote" || path.startsWith("/_authenticated/admin") || path.startsWith("/admin");
    },
  });

  return (
    <QueryClientProvider client={queryClient}>
      <NextdoorTracking />
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      {!bare && (
        <>
          {/* Spacer so the sticky mobile bar never covers page content */}
          <div aria-hidden className="h-[76px] md:hidden" />
          <MobileBookBar />
          <ChatLauncher />
        </>
      )}
    </QueryClientProvider>
  );
}
